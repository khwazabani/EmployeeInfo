package com.example.empinfo.service;

import com.example.empinfo.entity.Employee;
import com.example.empinfo.exception.EmployeeNotFoundException;
import com.example.empinfo.repository.EmployeeRepository;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;

import java.util.List;

@Service
@Transactional
public class EmployeeService {

    private final EmployeeRepository repository;

    public EmployeeService(EmployeeRepository repository) {
        this.repository = repository;
    }

    public Employee create(Employee employee) {
        employee.setEmpId(null); // id is generated by the database
        return repository.save(employee);
    }

    @Transactional(readOnly = true)
    public List<Employee> findAll() {
        return repository.findAll();
    }

    @Transactional(readOnly = true)
    public Employee findById(Long id) {
        return repository.findById(id).orElseThrow(() -> new EmployeeNotFoundException(id));
    }

    public Employee update(Long id, Employee updated) {
        Employee existing = findById(id);
        existing.setEmpName(updated.getEmpName());
        existing.setEmpDesignation(updated.getEmpDesignation());
        existing.setEmpSalary(updated.getEmpSalary());
        return repository.save(existing);
    }

    public void delete(Long id) {
        Employee existing = findById(id);
        repository.delete(existing);
    }
}
